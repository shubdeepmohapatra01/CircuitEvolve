"""Least-squares refit of a parameterised circuit template to a target unitary.

This is the machinery behind `pauli_subalgebra_dimension_recompression`, the retired
`rotation_count_minimal_block_refit` and `free_fermion_gaussian_resynthesis` - each of which rebuilt it
from raw numpy, under a time limit, once per rule (V4_README section 9).

    least_squares(template, target, x0, pinned=None, n=None)
        template(angles) -> op list;  target = dense unitary (or an op list + n)
        -> Fit(angles, distance, success, nfev): the angles minimising the PHASE-ALIGNED operator
           distance, which is exactly the quantity the judge charges to the ledger.
    pin_to_grid(template, target, x0, n, budget)
        greedily pin angles to the pi/4 grid, refitting the rest each time, while the distance stays
        within `budget`. Every pinned angle is one rotation gridsynth no longer pays for - this is the
        T-saving move, and `budget` is what the rule drew from the ledger.
    rank(unitaries)        numerical rank of a set of operators (dimension of the span)
    closure(generators)    the Lie algebra generated by a set of Hermitian Paulis, by commutators

The optimiser is `scipy.optimize.least_squares` on the real and imaginary parts of U - c V, with c the
aligning phase recomputed at every step, so global phase never enters the residual.
"""
from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np

from . import sim


@dataclass(frozen=True)
class Fit:
    angles: tuple
    distance: float            # phase-aligned operator distance at `angles`
    success: bool
    nfev: int
    message: str = ""


def _target_unitary(target, n=None) -> np.ndarray:
    if isinstance(target, np.ndarray):
        return target
    if n is None:
        raise ValueError("pass n when the target is an op list")
    return sim.unitary(target, n)


def _residual(U, V) -> np.ndarray:
    tr = np.trace(V.conj().T @ U)
    c = tr / abs(tr) if abs(tr) > 1e-300 else 1.0 + 0j
    D = U - c * V
    return np.concatenate([D.real.ravel(), D.imag.ravel()])


def least_squares(template, target, x0, n: int | None = None, pinned: dict | None = None,
                  max_nfev: int = 2000, xtol: float = 1e-14) -> Fit:
    """Fit `template`'s free angles to `target`. `pinned` = {index: fixed angle} is held constant."""
    from scipy.optimize import least_squares as _ls
    U = _target_unitary(target, n)
    k = U.shape[0].bit_length() - 1
    pinned = dict(pinned or {})
    free = [i for i in range(len(x0)) if i not in pinned]
    if not free:
        full = [pinned.get(i, x0[i]) for i in range(len(x0))]
        return Fit(tuple(full), sim.hs_distance(U, sim.unitary(template(full), k))["op"], True, 0, "all pinned")

    def build(theta_free):
        full = list(x0)
        for i, a in pinned.items():
            full[i] = a
        for j, i in enumerate(free):
            full[i] = float(theta_free[j])
        return full

    def f(theta_free):
        return _residual(U, sim.unitary(template(build(theta_free)), k))

    r = _ls(f, [float(x0[i]) for i in free], max_nfev=max_nfev, xtol=xtol)
    full = build(r.x)
    d = sim.hs_distance(U, sim.unitary(template(full), k))["op"]
    return Fit(tuple(full), float(d), bool(r.success), int(r.nfev), str(r.message))


def pin_to_grid(template, target, x0, n: int, budget: float, kmax: int = 2,
                order: str = "nearest") -> tuple:
    """Greedily pin angles onto the pi / 2^kmax grid while the refit still fits inside `budget`.

    -> (Fit, [pinned indices]). `kmax=2` is the pi/4 grid (Clifford+T, zero gridsynth cost)."""
    from . import angles as A
    U = _target_unitary(target, n)
    pinned: dict = {}
    cur = least_squares(template, U, x0, n=n)
    if cur.distance > budget:
        return cur, []
    cand = [i for i in range(len(x0)) if not A.on_grid(cur.angles[i])]
    if order == "nearest":
        cand.sort(key=lambda i: A.dyadic(cur.angles[i], kmax).distance)
    for i in cand:
        trial = dict(pinned)
        trial[i] = A.dyadic(cur.angles[i], kmax).angle
        f = least_squares(template, U, cur.angles, n=n, pinned=trial)
        if f.distance <= budget:
            pinned, cur = trial, f
    return cur, sorted(pinned)


# ------------------------------------------------------------------------------------------ algebra
def rank(ops_list, tol: float = 1e-9) -> int:
    """Numerical rank of a set of matrices seen as vectors: the dimension of their span."""
    if not len(ops_list):
        return 0
    M = np.stack([np.asarray(A).ravel() for A in ops_list])
    return int(np.linalg.matrix_rank(M, tol=tol))


def closure(generators, tol: float = 1e-9, max_dim: int = 256) -> list:
    """The Lie algebra generated by Hermitian matrices `generators`, as an orthonormal basis.

    Repeatedly adds i[A, B] for pairs already in the span until nothing new appears. The DIMENSION of
    this algebra bounds how many rotations a run of Pauli exponentials really needs: if d is smaller than
    the number of rotations, the run can be refitted with d of them (V4_README section 9,
    `pauli_subalgebra_dimension_recompression`)."""
    basis: list = []

    def add(A) -> bool:
        v = np.asarray(A, dtype=complex).ravel()
        for b in basis:
            v = v - np.vdot(b, v) * b
        nv = np.linalg.norm(v)
        if nv <= tol:
            return False
        basis.append(v / nv)
        return True

    mats = [np.asarray(g, dtype=complex) for g in generators]
    for g in mats:
        add(g)
    frontier = list(mats)
    while frontier and len(basis) < max_dim:
        new = []
        for i, A in enumerate(frontier):
            for B in mats:
                C = 1j * (A @ B - B @ A)
                if np.linalg.norm(C) > tol and add(C):
                    new.append(C)
                    mats.append(C)
                    if len(basis) >= max_dim:
                        break
            if len(basis) >= max_dim:
                break
        frontier = new
    shape = mats[0].shape if mats else (1, 1)
    return [b.reshape(shape) for b in basis]


def euler_template(k: int, pattern):
    """A template function from a fixed `pattern` of (gate, qubits) with `rz` slots filled from the angle
    vector, in order. `pattern` entries are ('rz', (q,)) for a free angle or (name, qubits) for a fixed
    Clifford."""
    slots = [i for i, (g, _) in enumerate(pattern) if g == "rz"]

    def template(angles):
        a = list(angles)
        out, j = [], 0
        for g, qs in pattern:
            if g == "rz":
                out.append(("rz", tuple(qs), float(a[j])))
                j += 1
            else:
                out.append((g, tuple(qs), None))
        return out
    template.n_angles = len(slots)                                      # type: ignore[attr-defined]
    return template
